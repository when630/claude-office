// 세션 하나를 **무엇이라고 부를지**. main과 렌더러가 함께 쓴다.
//
// mood 하나만 보면 되던 시절에는 이 파일이 필요 없었다. 서버 장애(main/collect.mjs의
// isBroken)가 mood 위에 얹히는 표시로 들어오면서, "그래서 이 세션은 어느 칸에 세는가"를
// 정하는 자리가 필요해졌다 — 그 답이 곳곳에서 갈라지면 화면이 자기 모순에 빠진다.
// 상단바가 `2 작업 중`인데 목록의 작업 중 묶음에는 셋이 있거나, 세는 칸의 합이 출근
// 인원을 넘거나 하는 식이다.

// 서버 장애를 **이 세션의 이름으로 쓰는가.**
//
// `worker.broken`은 "서버가 죽어 있다"는 사실이고 이 함수는 "그래서 그렇게 부를 것인가"다.
// 둘을 가르는 이유는 **입력 대기가 먼저이기 때문이다** — 서버가 죽어 있어도 나를 부르고
// 있다면 그쪽이 더 급한 소식이고, 그걸 서버 장애로 덮으면 정작 답해야 할 때 신호가
// 사라진다(캔버스에서 느낌표가 어지러움보다 앞인 것과 같은 판단이다).
export function showsBroken(worker) {
  return Boolean(worker?.broken) && worker.mood !== 'waiting';
}
